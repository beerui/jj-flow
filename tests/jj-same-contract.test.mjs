test('jj-same write plane is the single home for init/ANL/ensureDispatch forbids', () => {
  const routing = fs.readFileSync(path.join(root, 'skills/jj-same/references/artifact-routing.md'), 'utf8')
  assert.match(skill, /## Write plane \(do not collapse\)/)
  assert.match(skill, /Never `jj ralph init` CLI/)
  assert.match(skill, /Do \*\*not\*\* call `ensureDispatchRalphRuns`/)
  assert.match(routing, /SKILL \*\*Write plane\*\*/)
  assert.doesNotMatch(routing, /Never `jj ralph init` CLI/)
  assert.doesNotMatch(routing, /same does \*\*not\*\* call `ensureDispatchRalphRuns`/)
  assert.match(happy, /SKILL \*\*Write plane\*\*/)
  assert.doesNotMatch(happy, /Do not call `ensureDispatchRalphRuns`/)
})

