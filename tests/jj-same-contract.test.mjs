const spawn = fs.readFileSync(path.join(root, 'skills/jj/references/assignment-spawn.md'), 'utf8')

test('jj-same conversational path writes this-round assignment then researches then spawns', () => {
  assert.match(skill, /Parent chat is \*\*team-lead\*\*/)
  assert.match(skill, /Conversational path \(客服; must not skip\)/)
  assert.match(skill, /ASSIGNMENT-RESEARCH-<target>/)
  assert.match(skill, /ASSIGNMENT-HANDOFF-<target>/)
  assert.match(skill, /Call `spawn_subagent` \(`jj-researcher`; missing → `general-purpose`\) this turn/)
  assert.match(skill, /Spawn `jj-implementer` \(missing → `general-purpose`\)/)
  assert.match(skill, /assignment-spawn\.md/)
  assert.match(spawn, /派遣调研/)
  assert.match(spawn, /派遣交接实施/)
  assert.match(spawn, /\[research\]/)
  assert.match(spawn, /\[implementer\]/)
  assert.match(spawn, /description \*\*starts with\*\*/)
  assert.match(spawn, /resume_from/)
  assert.match(spawn, /inherits cwd/)
  assert.match(spawn, /Occupancy/)
  assert.match(spawn, /审查还在跑/)
  assert.match(spawn, /Do not wait silently/)
  assert.match(skill, /Do not `search_replace` in the parent/)
  assert.match(skill, /\*\*Do not\*\* port business code in this chat/)
  assert.match(skill, /\*\*Do not\*\* treat dispatch `distribution_prompt` as the worker spec or 人设提示词/)
  assert.doesNotMatch(skill, /## Happy path/)
  assert.match(skill, /Ralph-handoff-first/)
  assert.match(skill, /EXECUTION_READY/)
  assert.match(skill, /HANDOFF_READY/)
  assert.match(skill, /This skill's `references\/` are not a startup checklist/)
  assert.match(happy, /ASSIGNMENT-RESEARCH/)
  assert.match(happy, /ASSIGNMENT-HANDOFF/)
  assert.match(happy, /assignment-spawn\.md/)
})

